"""Generate synthetic monthly counts, train, evaluate and serialize a baseline model."""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import platform
import tempfile
from typing import Any
import sys

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error

from features.invoice_volume import FEATURE_COLUMNS, MIN_HISTORY, build_feature_row, build_supervised_features

ROOT = Path(__file__).resolve().parents[2]
DATA_PATH = ROOT / "data" / "synthetic_monthly_invoice_volume.csv"
MODEL_PATH = ROOT / "models" / "nop_invoice_volume_model.joblib"
METRICS_PATH = ROOT / "evaluation" / "evaluation_metrics.json"
BASELINE_PATH = ROOT / "evaluation" / "baseline_comparison.json"
METADATA_PATH = ROOT / "models" / "model_metadata.json"
MODEL_ID = "nop-monthly-invoice-volume-rf"
MODEL_VERSION = "1.0.0"
RANDOM_SEED = 20261103
DATA_COLUMNS = ("period", "invoice_count", "data_mode", "provenance")


def _validate_generation_parameters(observations: int, seed: int) -> None:
    if isinstance(observations, bool) or not isinstance(observations, (int, np.integer)) or observations < 121:
        raise ValueError("observations must be at least 121 for lagged train/test development")
    if isinstance(seed, bool) or not isinstance(seed, (int, np.integer)) or seed < 0:
        raise ValueError("seed must be a non-negative integer")


def _synthetic_frame(observations: int, seed: int) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    periods = pd.period_range("2011-01", periods=observations, freq="M")
    elapsed = np.arange(observations, dtype=float)
    annual = 16.0 * np.sin(2 * np.pi * (elapsed % 12) / 12 - 0.55)
    secondary = 4.0 * np.cos(4 * np.pi * (elapsed % 12) / 12 + 0.3)
    noise = rng.normal(loc=0.0, scale=3.5, size=observations)
    counts = np.maximum(0, np.rint(145.0 + 0.14 * elapsed + annual + secondary + noise)).astype(int)
    return pd.DataFrame({
        "period": periods.astype(str),
        "invoice_count": counts,
        "data_mode": "synthetic",
        "provenance": f"Generated by src/training/train_invoice_volume.py; seed={seed}; illustrative only",
    })


def generate_synthetic_dataset(output_path: Path = DATA_PATH, *, observations: int = 180, seed: int = RANDOM_SEED) -> pd.DataFrame:
    """Create a reproducible illustrative series; it contains no NOP observations."""
    _validate_generation_parameters(observations, seed)
    observations, seed = int(observations), int(seed)
    frame = _synthetic_frame(observations, seed)
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(output_path, index=False)
    return frame


def _make_model(seed: int) -> RandomForestRegressor:
    return RandomForestRegressor(
        n_estimators=300,
        max_depth=8,
        min_samples_leaf=2,
        max_features=0.9,
        random_state=seed,
        n_jobs=1,
    )


def _atomic_write_json(path: Path, value: Any) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp_name: str | None = None
    try:
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, prefix=path.name + ".", suffix=".tmp", delete=False) as stream:
            temp_name = stream.name
            json.dump(value, stream, indent=2)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temp_name, path)
    finally:
        if temp_name and os.path.exists(temp_name):
            os.unlink(temp_name)


def _atomic_dump_joblib(path: Path, value: Any) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp_name: str | None = None
    try:
        with tempfile.NamedTemporaryFile("wb", dir=path.parent, prefix=path.name + ".", suffix=".tmp", delete=False) as stream:
            temp_name = stream.name
        joblib.dump(value, temp_name)
        with open(temp_name, "r+b") as stream:
            os.fsync(stream.fileno())
        os.replace(temp_name, path)
    finally:
        if temp_name and os.path.exists(temp_name):
            os.unlink(temp_name)


def _recursive_forecast(model: Any, history_periods: list[str], history_counts: list[float], future_periods: list[str]) -> list[float]:
    periods = list(history_periods)
    counts = list(history_counts)
    predictions: list[float] = []
    for period in future_periods:
        row = build_feature_row(period, periods, counts)
        raw_prediction = np.asarray(model.predict(pd.DataFrame([row], columns=FEATURE_COLUMNS)), dtype=float)
        if raw_prediction.shape != (1,) or not np.isfinite(raw_prediction[0]):
            raise ValueError("model returned an invalid non-finite prediction")
        estimate = max(0.0, float(raw_prediction[0]))
        predictions.append(estimate)
        periods.append(period)
        counts.append(estimate)
    return predictions


def train_and_evaluate(
    data_path: Path = DATA_PATH,
    model_path: Path = MODEL_PATH,
    metadata_path: Path = METADATA_PATH,
    metrics_path: Path = METRICS_PATH,
    baseline_path: Path = BASELINE_PATH,
    *,
    seed: int = RANDOM_SEED,
) -> dict[str, Any]:
    """Fit on the chronological first 80%; evaluate a recursive future holdout."""
    _validate_generation_parameters(121, seed)
    seed = int(seed)
    data_path = Path(data_path)
    if not data_path.exists():
        frame = generate_synthetic_dataset(data_path, seed=seed)
    else:
        frame = pd.read_csv(data_path)
    if tuple(frame.columns) != DATA_COLUMNS:
        raise ValueError(f"synthetic training data must have exactly these columns in order: {', '.join(DATA_COLUMNS)}")
    expected_provenance = f"Generated by src/training/train_invoice_volume.py; seed={seed}; illustrative only"
    if frame["data_mode"].isna().any() or not frame["data_mode"].eq("synthetic").all():
        raise ValueError("every training row must be explicitly marked synthetic")
    if frame["provenance"].isna().any() or not frame["provenance"].eq(expected_provenance).all():
        raise ValueError("training data provenance does not match the selected generator and seed")

    frame = frame.copy()
    frame["period"] = pd.PeriodIndex(frame["period"], freq="M").astype(str)
    expected_frame = _synthetic_frame(len(frame), seed)
    if frame["period"].tolist() != expected_frame["period"].tolist():
        raise ValueError("training periods do not match the reproducible monthly generator output")
    try:
        observed_counts = pd.to_numeric(frame["invoice_count"], errors="raise").astype(float).tolist()
    except (TypeError, ValueError) as exc:
        raise ValueError("invoice_count must contain numeric generated values") from exc
    if observed_counts != expected_frame["invoice_count"].astype(float).tolist():
        raise ValueError("training target values do not match the reproducible synthetic generator output")
    frame["invoice_count"] = observed_counts
    features, targets = build_supervised_features(frame)
    count = len(frame)
    split_index = int(count * 0.8)
    if split_index <= MIN_HISTORY or count - split_index < 12:
        raise ValueError("need at least 12 chronological holdout months after the training history")
    train_rows = split_index - MIN_HISTORY
    x_train, y_train = features.iloc[:train_rows], targets.iloc[:train_rows]
    model = _make_model(seed)
    model.fit(x_train, y_train)

    periods = frame["period"].tolist()
    values = frame["invoice_count"].astype(float).tolist()
    test_periods = periods[split_index:]
    actual = values[split_index:]
    train_periods = periods[:split_index]
    train_history = values[:split_index]
    predicted = _recursive_forecast(model, train_periods, train_history, test_periods)

    baseline: list[float] = []
    baseline_history = list(train_history)
    for _period in test_periods:
        estimate = baseline_history[-1]
        baseline.append(estimate)
        baseline_history.append(estimate)

    metrics = {
        "evaluation_mode": "recursive multi-step chronological holdout",
        "train_observations": int(split_index),
        "supervised_train_rows": int(train_rows),
        "test_observations": int(len(test_periods)),
        "train_period_start": periods[0],
        "train_period_end": periods[split_index - 1],
        "test_period_start": test_periods[0],
        "test_period_end": test_periods[-1],
        "mae": float(mean_absolute_error(actual, predicted)),
        "rmse": float(np.sqrt(mean_squared_error(actual, predicted))),
        "prediction_policy": "recursive; holdout targets are never fed into later holdout features",
    }
    baseline_metrics = {
        "baseline": "previous_period_naive_recursive",
        "definition": "First forecast repeats the final training count; each later forecast repeats the previous baseline prediction.",
        "evaluation_mode": metrics["evaluation_mode"],
        "mae": float(mean_absolute_error(actual, baseline)),
        "rmse": float(np.sqrt(mean_squared_error(actual, baseline))),
        "model_mae": metrics["mae"],
        "model_rmse": metrics["rmse"],
        "mae_change_vs_baseline": float(metrics["mae"] - mean_absolute_error(actual, baseline)),
        "rmse_change_vs_baseline": float(metrics["rmse"] - np.sqrt(mean_squared_error(actual, baseline))),
    }

    # The holdout is evaluated using the pre-holdout estimator. After that
    # evaluation is frozen, fit the deliverable estimator on all available
    # history; this is the conventional final refit for future inference.
    deployment_model = _make_model(seed)
    deployment_model.fit(features, targets)

    try:
        source_reference = data_path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        source_reference = str(data_path.resolve())
    provenance = {
        "data_mode": "synthetic",
        "source": source_reference,
        "source_sha256": hashlib.sha256(data_path.read_bytes()).hexdigest(),
        "generation_method": "145 + 0.14*month_index + annual and semiannual sinusoidal components + seeded Normal(0, 3.5) noise; rounded and floored at zero",
        "random_seed": seed,
        "dataset_observations": count,
        "dataset_period_start": periods[0],
        "dataset_period_end": periods[-1],
        "deployment_fit_supervised_rows": int(len(targets)),
        "deployment_training_history_end": periods[-1],
        "evaluation_model_training_history_end": periods[split_index - 1],
        "evaluation_holdout_period_start": test_periods[0],
        "evaluation_holdout_period_end": test_periods[-1],
        "actual_nop_data_used": False,
    }
    training_config = {
        "algorithm": "sklearn.ensemble.RandomForestRegressor",
        "parameters": model.get_params(deep=False),
        "environment": {
            "python": platform.python_version(),
            "scikit_learn": sklearn.__version__,
            "numpy": np.__version__,
            "pandas": pd.__version__,
            "joblib": joblib.__version__,
        },
        "chronological_train_fraction": 0.8,
        "holdout_strategy": "recursive forecast from final training month for the entire holdout horizon",
        "deployment_refit": "After holdout evaluation, refit the serialized estimator on all available supervised observations; holdout metrics remain from the pre-holdout estimator.",
        "deployment_training_history_end": periods[-1],
        "feature_columns": list(FEATURE_COLUMNS),
    }
    limitations = [
        "Trained and evaluated exclusively on reproducible synthetic data; metrics do not estimate NOP business performance.",
        "Synthetic counts do not encode NOP source scope, invoice lifecycle, holidays, reporting lag, operational changes or business meaning.",
        "Only calendar and lagged counts are used; no exogenous business drivers are included.",
        "Recursive forecast errors may compound over longer horizons; no prediction intervals are provided.",
        "A supplied history replaces the bundled synthetic history at inference but is not validated or approved by this model package.",
    ]
    metadata = {
        "model_identifier": MODEL_ID,
        "model_version": MODEL_VERSION,
        "algorithm": training_config["algorithm"],
        "training_timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "training_data_provenance": provenance,
        "data_mode": "synthetic",
        "target_description": "Synthetic illustrative monthly invoice-volume count; not an approved NOP target.",
        "feature_definitions": {
            "year": "Calendar year of the prediction month.",
            "quarter": "Calendar quarter of the prediction month.",
            "month_01..month_12": "One-hot indicators for the prediction month-of-year.",
            "lag_1, lag_3, lag_6, lag_12": "Observed or recursively predicted counts 1, 3, 6 and 12 months before the prediction month.",
        },
        "training_configuration": training_config,
        "evaluation_metrics": metrics,
        "baseline_comparison": baseline_metrics,
        "known_limitations": limitations,
    }
    bundle = {
        "artifact_format_version": 1,
        "model": deployment_model,
        "model_identifier": MODEL_ID,
        "model_version": MODEL_VERSION,
        "feature_columns": list(FEATURE_COLUMNS),
        "history_periods": periods,
        "history_counts": values,
        "training_data_provenance": provenance,
        "data_mode": "synthetic",
        "known_limitations": limitations,
        "target_description": metadata["target_description"],
    }

    _atomic_dump_joblib(Path(model_path), bundle)
    metadata["model_artifact_sha256"] = hashlib.sha256(Path(model_path).read_bytes()).hexdigest()
    _atomic_write_json(Path(metrics_path), metrics)
    _atomic_write_json(Path(baseline_path), baseline_metrics)
    _atomic_write_json(Path(metadata_path), metadata)
    return {"metadata": metadata, "metrics": metrics, "baseline": baseline_metrics, "model_path": str(model_path)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--observations", type=int, default=180)
    parser.add_argument("--seed", type=int, default=RANDOM_SEED)
    args = parser.parse_args()
    generate_synthetic_dataset(DATA_PATH, observations=args.observations, seed=args.seed)
    result = train_and_evaluate(DATA_PATH, seed=args.seed)
    print(json.dumps({"metrics": result["metrics"], "baseline": result["baseline"], "model_path": result["model_path"]}, indent=2))


if __name__ == "__main__":
    main()
